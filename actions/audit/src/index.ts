import {
  analyzeSite,
  AuditError,
  buildReport,
  renderMarkdownReport,
  type AuditReport,
} from "@llm-seo-toolbox/core";

import { pullRequestContext, upsertPullRequestComment } from "./comment";
import { ActionInputError, readInputs, type ActionInputs } from "./inputs";
import { setOutput, writeStepSummary } from "./outputs";
import { renderPlainComment } from "./plain";

const MARKER = "llm-seo-toolbox-audit-report";
const USER_AGENT =
  "LLMSEOToolbox-Action/0.1 (+https://github.com/ABradwell/llm-seo-toolbox; automated audit)";

function runUrl(env: NodeJS.ProcessEnv = process.env): string | undefined {
  if (!env.GITHUB_SERVER_URL || !env.GITHUB_REPOSITORY || !env.GITHUB_RUN_ID) return undefined;
  return `${env.GITHUB_SERVER_URL}/${env.GITHUB_REPOSITORY}/actions/runs/${env.GITHUB_RUN_ID}`;
}

function logReport(report: AuditReport): void {
  console.log(`Target: ${report.finalUrl}`);
  console.log(
    `Profile: ${report.classification.label} (${
      report.classification.method === "override" ? "pinned" : "auto"
    }, ${report.classification.confidence}% confidence)`,
  );
  console.log(`Score: ${report.score}/100 · Grade ${report.grade} · ${report.gradeLabel}`);
  for (const id of ["discovery", "access", "parseability", "structured"] as const) {
    const pillar = report.pillars[id];
    if (pillar) console.log(`  ${pillar.name}: ${pillar.score}/100 (${pillar.status})`);
  }
}

async function commentOnPullRequest(body: string, enabled: boolean): Promise<void> {
  if (!enabled) return;

  const context = pullRequestContext();
  if (!context) {
    console.log("No pull request context or token available; skipping the PR comment.");
    return;
  }

  try {
    const result = await upsertPullRequestComment(context, MARKER, body);
    console.log(`PR comment ${result.action}${result.url ? `: ${result.url}` : ""}`);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.warn(`::warning::Could not write the pull request comment: ${message}`);
  }
}

function summaryMarkdown(markdown: string): string {
  return markdown.replace(/<!--[^>]*-->\n\n/, "").trimEnd();
}

async function audit(inputs: ActionInputs): Promise<void> {
  console.log(`Auditing ${inputs.url} (timeout ${inputs.timeoutMs}ms)`);

  let report: AuditReport;
  try {
    const result = await analyzeSite(inputs.url, {
      siteType: inputs.siteType,
      timeoutMs: inputs.timeoutMs,
      userAgent: USER_AGENT,
      resolveLinks: inputs.resolveLinks,
      agentFetch: inputs.agentFetch,
      cache: false,
    });
    report = buildReport(result, {
      minScore: inputs.minScore,
      minGrade: inputs.minGrade,
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    const hint = error instanceof AuditError ? error.hint : undefined;
    console.error(`::error::${message}`);
    if (hint) console.error(`Hint: ${hint}`);

    const failure = [
      `<!-- ${MARKER} -->`,
      "",
      "## ❌ LLM SEO Toolbox audit could not run",
      "",
      `**Target:** ${inputs.url}`,
      "",
      `**Error:** ${message}`,
      ...(hint ? ["", `**Hint:** ${hint}`] : []),
      "",
      "*Generated by [LLM SEO Toolbox](https://github.com/ABradwell/llm-seo-toolbox).*",
    ].join("\n");

    writeStepSummary(failure);
    setOutput("passed", "false");
    setOutput("report-json", JSON.stringify({ url: inputs.url, error: message }));
    await commentOnPullRequest(failure, inputs.commentOnPr);
    process.exitCode = 1;
    return;
  }

  logReport(report);

  const markdown =
    inputs.reportStyle === "plain"
      ? renderPlainComment(report, { marker: MARKER, runUrl: runUrl() })
      : renderMarkdownReport(report, {
          marker: MARKER,
          title: "LLM SEO Toolbox audit",
          runUrl: runUrl(),
        });
  writeStepSummary(summaryMarkdown(markdown));

  setOutput("score", String(report.score));
  setOutput("grade", report.grade);
  setOutput("passed", String(report.passed ?? false));
  setOutput("report-json", JSON.stringify(report));

  await commentOnPullRequest(markdown, inputs.commentOnPr);

  if (!report.passed) {
    const gate = report.thresholds;
    const misses: string[] = [];
    if (gate && !gate.scorePassed) misses.push(`score ${report.score} < ${gate.minScore}`);
    if (gate && !gate.gradePassed) misses.push(`grade ${report.grade} < ${gate.minGrade}`);
    console.error(
      `::error::LLM SEO Toolbox gate failed: ${misses.join(", ") || "threshold missed"}`,
    );
    process.exitCode = 1;
    return;
  }

  console.log("LLM SEO Toolbox gate passed.");
}

async function main(): Promise<void> {
  try {
    const inputs = readInputs();
    await audit(inputs);
  } catch (error) {
    if (error instanceof ActionInputError) {
      console.error(`::error::${error.message}`);
      setOutput("passed", "false");
      process.exitCode = 1;
      return;
    }

    const message = error instanceof Error ? error.message : String(error);
    console.error(`::error::LLM SEO Toolbox action failed: ${message}`);
    setOutput("passed", "false");
    process.exitCode = 1;
  }
}

void main();
